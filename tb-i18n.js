  const COLOR_KEYS = [
    'color_red',
    'color_blue',
    'color_green',
    'color_yellow',
    'color_purple',
    'color_orange',
  ];

  function colorName(i) {
    return t(COLOR_KEYS[((i % COLOR_KEYS.length) + COLOR_KEYS.length) % COLOR_KEYS.length]);
  }

  /**
   * @param {string} key
   * @param {string} [fallback] usado apenas se a chave não existir em nenhum catálogo
   * @returns {string}
   */
  function t(key, fallback) {
    if (!ready()) return I18N.pt[key] || fallback || key;
    const lang = (C.ld().lang || 'pt').slice(0, 2);
    const dict = I18N[lang] || I18N.pt;
    return dict[key] || I18N.pt[key] || fallback || key;
  }

  function detectLanguage(navLang) {
    const l = String(navLang || '').toLowerCase();
    if (l.indexOf('pt') === 0) return 'pt';
    if (l.indexOf('es') === 0) return 'es';
    if (l.indexOf('en') === 0) return 'en';
    return 'en'; // padrao internacional para idiomas nao suportados
  }

  function setLanguage(lang) {
    const s = C.ld();
    s.lang = lang;
    C.sv(s);
    const langMap = { pt: 'pt-BR', en: 'en', es: 'es' };
    const code = (lang || 'pt').slice(0, 2);
    if (typeof document !== 'undefined') document.documentElement.lang = langMap[code] || 'pt-BR';
    applyI18n();
    C.showToast('🌐', t('lang_changed'), lang.toUpperCase());
  }

  function applyDataI18n(root) {
    const scope =
      root == null ? document : typeof root === 'string' ? document.querySelector(root) : root;
    if (!scope) return;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
  }

